def _normalized(value: str) -> str:
    return ' '.join(unicodedata.normalize('NFC', value).casefold().split())


_CODES = {code: name for name, code in _CANONICAL_COUNTRIES}
_NAMES: dict[str, set[str]] = {}
for _name, _code in _CANONICAL_COUNTRIES:
    _NAMES.setdefault(_normalized(_name), set()).add(_code)


def parse_location(value: str) -> tuple[str, str] | None:
    """Two whole components, never prefix/substring or guessed country codes."""
    if not isinstance(value, str) or value.count(',') != 1:
        return None
    city_raw, country_raw = value.split(',')
    city, country = _normalized(city_raw), _normalized(country_raw)
    if not city or not country:
        return None
    if re.fullmatch(r'[a-z]{3}', country, re.ASCII):
        code = country.upper()
        if code not in _CODES:
            return None
    else:
        matches = _NAMES.get(country, set())
        if len(matches) != 1:
            return None
        code = next(iter(matches))
    return city, code


def equivalent_location(approved: str, caption: str) -> bool:
    left, right = parse_location(approved), parse_location(caption)
    return left is not None and right is not None and left == right


def press_keys(answer: str) -> tuple[str, ...] | None:
    """Only the positively supported ASCII logical keys enter BrowserSkill IPC."""
    if not isinstance(answer, str) or not 0 < len(answer) <= 128:
        return None
    safe = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789,.-' "
    if any(char not in safe for char in answer):
        return None
    return tuple('Space' if char == ' ' else char for char in answer)
